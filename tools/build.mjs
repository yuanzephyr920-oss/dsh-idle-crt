/**
 * 构建：把 src/client/index.js（单文件 ESM，零运行时依赖）打成 IIFE
 * 输出到 lib/plate.js，由宿主半区经 /dsh-idle-crt/client.js 下发。
 *
 * 注意产物叫 plate.js 而不是 client.js：后者是 `dsh.client` 客户端模块
 * （设置页），由宿主 Loader 直接扫描 import，两者不能混。
 *
 * 之所以自己打包而不是走客户端模块注册表：待机画面需要一块盖住整页、
 * 完全接管指针事件的自挂载浮层；那条通道是给 React 槽位组件用的。
 */
import { build } from 'esbuild'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import fs from 'node:fs'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const outfile = path.join(root, 'lib', 'plate.js')
fs.mkdirSync(path.dirname(outfile), { recursive: true })

const result = await build({
  entryPoints: [path.join(root, 'src', 'client', 'index.js')],
  outfile,
  bundle: true,
  format: 'iife',
  platform: 'browser',
  target: ['chrome120'],
  minify: true,
  sourcemap: false,
  legalComments: 'none',
  charset: 'utf8',
  banner: { js: '/* dsh-idle-crt - browser half - generated by tools/build.mjs */' },
  logLevel: 'info',
  metafile: true,
})

const bytes = fs.statSync(outfile).size
console.log(`[build] lib/plate.js  ${(bytes / 1024).toFixed(1)} KiB`)
const outputs = result.metafile.outputs
for (const [file, info] of Object.entries(outputs)) {
  if (info.bytes > 200000) {
    for (const [dep, d] of Object.entries(info.inputs)) {
      if (d.bytesInOutput > 20000) console.log(`        ${dep}  ${(d.bytesInOutput / 1024).toFixed(1)} KiB`)
    }
  }
}
